_RECOMMENDATIONS = {"STRONG_HIRE", "HIRE", "CONSIDER", "WEAK", "NO_HIRE"}


def _clamp_score(value: Any, default: float = 0.0) -> float:
    try:
        score = float(value)
    except (TypeError, ValueError):
        score = default
    return round(max(0.0, min(100.0, score)), 2)


def _as_text_list(value: Any, fallback: list[str]) -> list[str]:
    if isinstance(value, list):
        cleaned = [str(item).strip() for item in value if str(item).strip()]
        return cleaned or fallback
    if isinstance(value, str) and value.strip():
        return [value.strip()]
    return fallback


def _candidate_turns(transcript: list[dict]) -> list[dict]:
    return [turn for turn in transcript if turn.get("speaker") in {"candidate", "user"}]


def _score_average(scores: list[dict]) -> float:
    if not scores:
        return 0.0
    return round(
        sum(float(score.get("raw_score") or 0.0) for score in scores) / len(scores), 2
    )


def _fallback_report(
    state: dict[str, Any] | None, candidate_assessment_id: str
) -> dict[str, Any]:
    question_scores = list((state or {}).get("question_scores") or [])
    violations = list((state or {}).get("violations") or [])
    avg_10 = _score_average(question_scores)
    avg_100 = round(avg_10 * 10, 2)

    grouped: dict[str, list[dict]] = {}
    for score in question_scores:
        grouped.setdefault(str(score.get("section") or "General"), []).append(score)

    def difficulty(items: list[dict]) -> str | None:
        values = [
            str(item.get("difficulty") or "")
            for item in items
            if item.get("difficulty")
        ]
        if "hard" in values:
            return "hard"
        if "medium" in values:
            return "medium"
        return values[0] if values else None

    skill_scores = {
        section: {
            "priority_score": 5,
            "raw_score": _score_average(items),
            "weighted_score": round(_score_average(items) * 0.5, 2),
            "difficulty_reached": difficulty(items),
            "signals_demonstrated": [
                signal
                for item in items
                for signal in item.get("signals_demonstrated", [])
            ][:8],
            "signals_missing": [
                signal for item in items for signal in item.get("signals_missing", [])
            ][:8],
            "summary": f"Average score {_score_average(items)}/10 across {len(items)} answer(s).",
        }
        for section, items in grouped.items()
    } or {
        "General": {
            "priority_score": 5,
            "raw_score": avg_10,
            "weighted_score": round(avg_10 * 0.5, 2),
            "difficulty_reached": None,
            "signals_demonstrated": [],
            "signals_missing": [],
            "summary": "No detailed turn scores were available; report generated from the session transcript.",
        }
    }

    section_summaries = {
        section: {
            "summary": f"Covered {len(items)} evaluated answer(s) in {section}.",
            "avg_score": _score_average(items),
            "difficulty_reached": difficulty(items),
            "questions_asked": len(items),
        }
        for section, items in grouped.items()
    }

    best = max(
        question_scores,
        key=lambda item: float(item.get("raw_score") or 0.0),
        default=None,
    )
    weakest = min(
        question_scores,
        key=lambda item: float(item.get("raw_score") or 0.0),
        default=None,
    )
    strengths = [
        signal
        for score in question_scores
        for signal in score.get("signals_demonstrated", [])
    ][:4]
    concerns = [
        signal
        for score in question_scores
        for signal in score.get("signals_missing", [])
    ][:4]

    if avg_100 >= 85:
        recommendation = "STRONG_HIRE"
    elif avg_100 >= 70:
        recommendation = "HIRE"
    elif avg_100 >= 55:
        recommendation = "CONSIDER"
    elif avg_100 >= 40:
        recommendation = "WEAK"
    else:
        recommendation = "NO_HIRE"

    def highlight(score: dict | None) -> dict | None:
        if not score:
            return None
        return {
            "question": str(score.get("question") or ""),
            "turn_number": int(score.get("turn_number") or 0),
            "section": str(score.get("section") or "General"),
            "difficulty_at_time": score.get("difficulty"),
            "reason": str(
                score.get("reasoning") or "Selected from turn-level scoring."
            ),
        }

    violation_summary = (
        {
            "total_irrelevant": sum(
                1 for item in violations if item.get("violation_type") == "irrelevant"
            ),
            "total_silences": sum(
                1 for item in violations if item.get("violation_type") == "silence"
            ),
            "terminated_early": (state or {}).get("session_status") == "TERMINATED",
            "entries": violations,
        }
        if violations
        else None
    )

    return {
        "skill_scores": skill_scores,
        "technical_dimension_score": avg_100,
        "score_evidence": strengths or ["Interview transcript captured for review."],
        "score_summary": f"Holistic interview aggregate score is {avg_100}/100.",
        "behavioural_score": avg_100,
        "behavioural_evidence": strengths
        or ["No separate behavioural evidence was isolated."],
        "behavioural_summary": "Behavioural assessment is based on available interview signals.",
        "cultural_fit_score": avg_100,
        "cultural_fit_evidence": strengths
        or ["No separate cultural-fit evidence was isolated."],
        "cultural_fit_summary": "Cultural-fit assessment is based on available interview signals.",
        "tone_classification_score": None,
        "tone_distribution": None,
        "section_summaries": section_summaries,
        "overall_score": avg_100,
        "hiring_recommendation": recommendation,
        "overall_narrative": "This holistic report was generated from the completed interview transcript and turn-level evaluations. It summarizes the strongest available evidence, observed concerns, and a hiring recommendation for recruiter review.",
        "strengths": strengths or ["Completed the interview session."],
        "concerns": concerns
        or ["No major concerns were identified from available scoring."],
        "violation_summary": violation_summary,
        "best_answer": highlight(best),
        "weakest_answer": highlight(weakest),
        "recommendation_reasoning": f"Recommendation is based on an aggregate interview score of {avg_100}/100 for candidate assessment {candidate_assessment_id}.",
    }


def _normalize_report(raw: dict[str, Any], fallback: dict[str, Any]) -> dict[str, Any]:
    report = {**fallback, **(raw or {})}

    for key in [
        "technical_dimension_score",
        "behavioural_score",
        "cultural_fit_score",
        "overall_score",
    ]:
        report[key] = _clamp_score(report.get(key), fallback.get(key, 0.0))

    for key in [
        "score_evidence",
        "behavioural_evidence",
        "cultural_fit_evidence",
        "strengths",
        "concerns",
    ]:
        report[key] = _as_text_list(report.get(key), fallback.get(key, []))

    for key in [
        "score_summary",
        "behavioural_summary",
        "cultural_fit_summary",
        "overall_narrative",
        "recommendation_reasoning",
    ]:
        report[key] = str(report.get(key) or fallback.get(key) or "").strip()

    recommendation = str(report.get("hiring_recommendation") or "CONSIDER").upper()
    report["hiring_recommendation"] = (
        recommendation if recommendation in _RECOMMENDATIONS else "CONSIDER"
    )

    if not isinstance(report.get("skill_scores"), dict) or not report["skill_scores"]:
        report["skill_scores"] = fallback["skill_scores"]
    if not isinstance(report.get("section_summaries"), dict):
        report["section_summaries"] = fallback["section_summaries"]
    if report.get("tone_classification_score") is not None:
        report["tone_classification_score"] = _clamp_score(
            report["tone_classification_score"]
        )
    if not isinstance(report.get("tone_distribution"), list):
        report["tone_distribution"] = None

    return report


def _build_transcript_text(transcript: list[dict]) -> str:
    lines: list[str] = []
    for index, turn in enumerate(transcript, start=1):
        speaker = "Interviewer" if turn.get("speaker") == "bot" else "Candidate"
        turn_number = turn.get("turn_number") or index
        section = turn.get("section") or "unknown"
        text = str(turn.get("text") or "").strip()
        if text:
            lines.append(f"[{speaker} Turn {turn_number} - Section: {section}]: {text}")
    return "\n".join(lines)


def _build_evals_text(question_scores: list[dict]) -> str:
    lines: list[str] = []
    for score in question_scores:
        lines.append(
            "[Turn {turn} Eval]: Score {raw}/10, Required signals hit: {hit}. "
            "Missing: {missing}. Feedback: {feedback}".format(
                turn=score.get("turn_number") or 0,
                raw=score.get("raw_score") or 0,
                hit=score.get("signals_demonstrated") or [],
                missing=score.get("signals_missing") or [],
                feedback=score.get("reasoning") or "",
            )
        )
    return "\n".join(lines)


async def run_holistic_evaluation(
    candidate_assessment_id: str,
    state: dict[str, Any] | None = None,
) -> bool:
    """Runs the final holistic evaluation based on interview_sessions transcript and violations."""
    try:
        ca_uuid = uuid.UUID(candidate_assessment_id)
    except ValueError:
        logger.error("Invalid UUID for evaluation: %s", candidate_assessment_id)
        return False

    session_id: uuid.UUID | None = None
    transcript: list[dict] = list((state or {}).get("transcript") or [])
    question_scores: list[dict] = list((state or {}).get("question_scores") or [])
    violations: list[dict] = list((state or {}).get("violations") or [])

    data = await get_interview_data_for_evaluation(ca_uuid)
    if data and data.get("session"):
        session = data["session"]
        session_id = session["id"]
        if not transcript:
            transcript = list(session.get("transcript") or [])
        if not violations:
            violations = list(session.get("violations") or [])

    if state and state.get("session_id"):
        session_id = uuid.UUID(str(state["session_id"]))

    if session_id is None:
        logger.warning("No interview data found for %s", candidate_assessment_id)
        return False

    if not _candidate_turns(transcript):
        logger.warning(
            "No candidate transcript turns found for %s", candidate_assessment_id
        )
        return False

    eval_state = {
        **(state or {}),
        "transcript": transcript,
        "question_scores": question_scores,
        "violations": violations,
    }
    fallback = _fallback_report(eval_state, candidate_assessment_id)

    user_message = (
        f"Transcript from interview_sessions.transcript:\n{_build_transcript_text(transcript)}\n\n"
        f"Turn-by-turn evaluations from live interview state:\n{_build_evals_text(question_scores)}\n"
        f"Violations from interview_sessions.violations: {json.dumps(violations, indent=2) if violations else 'None'}"
    )

    messages = [
        {"role": "system", "content": _HOLISTIC_SYSTEM_PROMPT},
        {"role": "user", "content": user_message},
    ]

    try:
        response_json = await evaluate(messages)
        eval_data = _normalize_report(json.loads(response_json), fallback)
    except Exception:
        logger.exception(
            "Failed to generate or parse holistic evaluation for %s", ca_uuid
        )
        eval_data = fallback

    await save_holistic_evaluation(ca_uuid, session_id, eval_data)
    logger.info("Holistic evaluation completed and saved for %s", ca_uuid)
    return True
