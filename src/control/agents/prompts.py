    "Classify response_type as exactly one of: answer, clarification, irrelevant. "
    "Silence, timers, disconnects, and obvious static routes are handled outside "
    "this LLM.\n\n"
    "Use answer when the candidate is attempting the active question. Set "
    "is_substantial true only when there is meaningful technical signal: a relevant "
    "concept, explanation, reasoning, comparison, example, approach, or trade-off. "
    "Set it false for filler, one-word, very vague, or nearly empty attempts. For "
    "substantial answers, set answer_strength to weak, adequate, or strong. Weak "
    "means mostly wrong or missing the core point. Adequate means partially correct "
    "but incomplete or unclear. Strong means the core technical point is answered "
