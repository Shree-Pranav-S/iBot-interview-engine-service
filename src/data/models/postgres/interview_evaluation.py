"""
InterviewEvaluation model.

Final holistic evaluation record generated by the post-interview Celery task.
One record per completed interview.

Primary data source for the recruiter report view — all dimension scores,
narratives, rankings, and hiring recommendations live here.

IMPORTANT: candidate_assessment_id is the sole reference key.
The UNIQUE constraint enforces one evaluation per candidate per assessment.
Owned by: interview-service
"""

import uuid
from datetime import datetime
from typing import TYPE_CHECKING

from sqlalchemy import Float, ForeignKey, Integer, Text
from sqlalchemy.dialects.postgresql import ARRAY, JSONB, TIMESTAMP, UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship
from sqlalchemy.sql import func

from src.data.models.postgres.base import Base

if TYPE_CHECKING:
    from src.data.models.postgres.interview_session import InterviewSession


class InterviewEvaluation(Base):
    __tablename__ = "interview_evaluations"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
        server_default=func.gen_random_uuid(),
    )

    # Sole cross-service reference key.
    # UNIQUE enforces one evaluation per candidate per assessment.
    candidate_assessment_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        nullable=False,
        unique=True,
        index=True,
    )

    # FK to interview_sessions for ORM relationship only
    session_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("interview_sessions.id", ondelete="CASCADE"),
        nullable=False,
        unique=True,
    )

    # ── Skill scores ──────────────────────────────────────────────────────────

    # Per-skill breakdown keyed by skill name.
    # Each entry: {priority_score, weighted_score, raw_score,
    #              difficulty_reached, signals_demonstrated,
    #              signals_missing, summary}
    # weighted_score = raw_score * (priority_score / 10)
    # Used to compute technical_dimension_score.
    skill_scores: Mapped[dict] = mapped_column(JSONB, nullable=False)

    # ── Dimension scores ──────────────────────────────────────────────────────

    # Priority-weighted average across all assessed skills, normalised to 0–100
    technical_dimension_score: Mapped[float] = mapped_column(Float, nullable=False)

    problem_solving_score: Mapped[float] = mapped_column(Float, nullable=False)
    problem_solving_evidence: Mapped[list[str]] = mapped_column(
        ARRAY(Text), nullable=False
    )
    problem_solving_summary: Mapped[str] = mapped_column(Text, nullable=False)

    communication_score: Mapped[float] = mapped_column(Float, nullable=False)
    communication_evidence: Mapped[list[str]] = mapped_column(
        ARRAY(Text), nullable=False
    )
    communication_summary: Mapped[str] = mapped_column(Text, nullable=False)

    behavioural_score: Mapped[float] = mapped_column(Float, nullable=False)
    behavioural_evidence: Mapped[list[str]] = mapped_column(ARRAY(Text), nullable=False)
    behavioural_summary: Mapped[str] = mapped_column(Text, nullable=False)

    cultural_fit_score: Mapped[float] = mapped_column(Float, nullable=False)
    cultural_fit_evidence: Mapped[list[str]] = mapped_column(
        ARRAY(Text), nullable=False
    )
    cultural_fit_summary: Mapped[str] = mapped_column(Text, nullable=False)

    # 0–100 aggregate from SpeechBrain — carries 5% weight in overall score.
    # Null if SpeechBrain produced insufficient data across the session.
    tone_classification_score: Mapped[float | None] = mapped_column(
        Float, nullable=True
    )
    # Per-turn SpeechBrain scores aggregated across the full interview.
    # Format: [{turn_number, confident, neutral, hesitant}, ...]
    tone_distribution: Mapped[list | None] = mapped_column(JSONB, nullable=True)

    # ── Section summaries ─────────────────────────────────────────────────────

    # Per-section narrative keyed by section name.
    # Each entry: {summary, avg_score, difficulty_reached, questions_asked}
    # Gives recruiters a quick section-level breakdown without reading
    # the full transcript.
    section_summaries: Mapped[dict] = mapped_column(
        JSONB, nullable=False, default=dict, server_default="{}"
    )

    # ── Overall score and recommendation ──────────────────────────────────────

    # Weighted composite:
    # technical 40% + problem_solving 20% + communication 15%
    # + behavioural 15% + cultural_fit 5% + tone 5%
    overall_score: Mapped[float] = mapped_column(Float, nullable=False)

    # STRONG_HIRE | HIRE | CONSIDER | WEAK | NO_HIRE
    hiring_recommendation: Mapped[str] = mapped_column(Text, nullable=False, index=True)

    # Populated if the recommendation was adjusted due to critical red flags
    recommendation_override_reason: Mapped[str | None] = mapped_column(
        Text, nullable=True
    )

    # 3–4 sentence holistic impression narrative
    overall_narrative: Mapped[str] = mapped_column(Text, nullable=False)

    # ── Strengths, concerns, red flags ───────────────────────────────────────

    # Up to 4 specific evidence-backed strengths
    strengths: Mapped[list[str]] = mapped_column(ARRAY(Text), nullable=False)

    # Up to 4 specific evidence-backed concerns
    concerns: Mapped[list[str]] = mapped_column(ARRAY(Text), nullable=False)

    # Critical and minor flags with description and severity.
    # Format: [{description, severity: "critical"|"minor"}, ...]
    red_flags: Mapped[list] = mapped_column(
        JSONB, nullable=False, default=list, server_default="[]"
    )

    # ── Violation summary ─────────────────────────────────────────────────────

    # Summary of session violations if any occurred.
    # Pulled from interview_sessions.violations and included here so the
    # recruiter report has a single data source.
    # Format: {total_irrelevant, total_silences, terminated_early, entries: [...]}
    # Null if no violations occurred.
    violation_summary: Mapped[dict | None] = mapped_column(JSONB, nullable=True)

    # ── Highlight answers ─────────────────────────────────────────────────────

    # Format: {question, turn_number, section, difficulty_at_time, reason}
    best_answer: Mapped[dict | None] = mapped_column(JSONB, nullable=True)

    # Format: {question, turn_number, section, difficulty_at_time, reason}
    weakest_answer: Mapped[dict | None] = mapped_column(JSONB, nullable=True)

    # LLM narrative justifying the hiring recommendation
    recommendation_reasoning: Mapped[str] = mapped_column(Text, nullable=False)

    # ── Ranking ───────────────────────────────────────────────────────────────

    # Candidate rank among all evaluated candidates in the same assessment.
    # Updated on every new evaluation completion in this assessment.
    rank_in_assessment: Mapped[int | None] = mapped_column(Integer, nullable=True)

    # Percentile 0–100, updated on every new evaluation completion
    percentile_in_assessment: Mapped[int | None] = mapped_column(Integer, nullable=True)

    # Total evaluated candidates at the time this ranking was computed
    total_candidates_evaluated: Mapped[int | None] = mapped_column(
        Integer, nullable=True
    )

    # ── Timestamps ────────────────────────────────────────────────────────────

    generated_at: Mapped[datetime] = mapped_column(
        TIMESTAMP(timezone=True), nullable=False, server_default=func.now()
    )

    # ── Relationships ─────────────────────────────────────────────────────────

    session: Mapped["InterviewSession"] = relationship(
        back_populates="evaluation",
        uselist=False,
    )

    def __repr__(self) -> str:
        return (
            f"<InterviewEvaluation candidate_assessment_id={self.candidate_assessment_id} "
            f"score={self.overall_score} recommendation={self.hiring_recommendation}>"
        )
